"""Inference-only matched-prompt pair evidence.

Experimental representation primitive, NOT a trained/validated Kaggle candidate.
Reference pairs must be generated by two *different* exact model labels from
the SAME original prompt and independently audited generation protocol.
This module never fits a model or accesses Kaggle/official data.

Inputs are frozen encoder embeddings supplied by the caller. Use on externally
held-out examples before considering integration with a strong champion.
"""
from __future__ import annotations

from dataclasses import dataclass
import numpy as np


@dataclass(frozen=True)
class PairEvidence:
    """Positive margin favors A; negative margin favors B."""
    margin: float
    agreement: float
    panels_used: int
    nearest_similarity: float


def _unit_vectors(array: np.ndarray, *, name: str) -> np.ndarray:
    arr = np.asarray(array, dtype=np.float64)
    if arr.ndim != 2 or arr.shape[1] < 2:
        raise ValueError(f"{name}: expected 2D vectors with d>=2")
    if not np.all(np.isfinite(arr)):
        raise ValueError(f"{name}: all values must be finite")
    norm = np.linalg.norm(arr, axis=1, keepdims=True)
    if np.any(norm < 1e-12):
        raise ValueError(f"{name}: zero-length embedding")
    return arr / norm


def matched_pair_evidence(
    query_embedding: np.ndarray,
    model_a_examples: np.ndarray,
    model_b_examples: np.ndarray,
    *,
    top_k: int = 16,
) -> PairEvidence:
    """Compare one query against paired A/B examples of identical prompts.

    The arrays A[i], B[i] must share prompt+source+generation settings.
    Select the top-k nearest *unlabeled pair centroids* by cosine similarity.
    Compute the geometric A-vs-B squared-distance contrast on each pair,
    normalize only by within-pair distance, then take the median.

    No training, class-dependent weighting, test-prompt clustering, or hidden
    label assumptions. A +margin is evidence, not a calibrated probability,
    and must not override a champion absent a locked full-stack transfer test.
    """
    a = _unit_vectors(model_a_examples, name="model_a_examples")
    b = _unit_vectors(model_b_examples, name="model_b_examples")
    q = _unit_vectors(
        np.asarray(query_embedding, dtype=np.float64).reshape(1, -1),
        name="query_embedding",
    )[0]
    if a.shape != b.shape or a.shape[1] != q.size:
        raise ValueError("A/B paired arrays and query must have identical dimension")
    if a.shape[0] < 2:
        raise ValueError("at least two matched prompt pairs are required")
    if not isinstance(top_k, int) or not 1 <= top_k <= a.shape[0]:
        raise ValueError("top_k must be an integer between 1 and pair count")

    centroids = 0.5 * (a + b)
    lengths = np.linalg.norm(centroids, axis=1)
    if np.any(lengths < 1e-12):
        raise ValueError("some pair centroids cancel: cannot retrieve by topic")
    similarities = centroids @ q / lengths
    # Stable sort fixes top-k selection under equal nearest similarities.
    selected = np.argsort(-similarities, kind="stable")[:top_k]

    direction = a[selected] - b[selected]
    direction_norm = np.linalg.norm(direction, axis=1)
    if np.any(direction_norm < 1e-12):
        raise ValueError("selected pairs have identical A/B embeddings")
    # (q - midpoint) dot (a - b) is half the B-vs-A squared
    # distance difference. Normalization limits dominating outlier pairs.
    margins = np.einsum(
        "nd,nd->n", q[None, :] - centroids[selected], direction
    ) / direction_norm
    median = float(np.median(margins))
    agreement = float(np.mean(np.sign(margins) == np.sign(median)))
    return PairEvidence(
        margin=median,
        agreement=agreement,
        panels_used=int(top_k),
        nearest_similarity=float(similarities[selected[0]]),
    )
